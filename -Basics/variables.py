# Python Variables
# A variable is used to store data.

# Creating variables
name = "Kartheek"
age = 21
height = 5.8
is_student = True

print(name)
print(age)
print(height)
print(is_student)


# Multiple variables
first_name, last_name = "Kartheek", "Lagisetti"

print(first_name)
print(last_name)


# Assigning the same value to multiple variables
x = y = z = 100

print(x)
print(y)
print(z)


# Changing a variable value
age = 21
print("Before:", age)

age = 22
print("After:", age)